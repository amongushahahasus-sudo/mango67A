import { strict as assert } from 'node:assert'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readFile } from 'node:fs/promises'
import { chromium, expect } from '@playwright/test'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
try {
  const context = await browser.newContext({ offline: true })
  // This smoke test starts after the separately tested first-visit tutorial.
  await context.addInitScript(() => localStorage.setItem('mango-fx-onboarding-v1', 'completed'))
  const page = await context.newPage()
  // Managed cloud Chromium blocks file:// by policy. Fulfill the identical
  // single HTML from disk with networking disabled; no server/assets are used.
  const documentUrl = 'http://127.0.0.1:5173/MANGO-FX.html'
  const html = await readFile(resolve(root, 'dist/MANGO-FX.html'), 'utf8')
  await page.route(documentUrl, route => route.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: html }))
  const errors = [], requests = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (/^https?:/.test(request.url()) && request.url() !== documentUrl) requests.push(request.url()) })
  await page.goto(documentUrl)
  await expect(page.getByRole('button', { name: '買い注文を出す', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^相場を(一時停止|再生)$/ })).toHaveCount(0)
  const lastMarketTime = () => page.evaluate(() => JSON.parse(localStorage.getItem('mango-fx-simulator-v1') || 'null')?.markets.USDJPY.at(-1).time ?? null)
  await expect.poll(lastMarketTime).not.toBeNull()
  const marketTime = await lastMarketTime()
  await expect.poll(lastMarketTime, { timeout: 7000 }).toBeGreaterThan(marketTime)
  await page.getByRole('button', { name: /^表示モード（/ }).click()
  await page.getByRole('dialog', { name: '表示モード', exact: true }).getByRole('button', { name: 'ガラス調', exact: true }).click()
  assert.equal(await page.locator('html').getAttribute('data-interface-style'), 'glass')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '買い注文を出す', exact: true }).click()
  await page.getByRole('button', { name: 'USD / JPYの買い建玉を決済', exact: true }).click()
  await page.getByRole('tab', { name: /取引履歴/ }).click()
  const panel = page.getByRole('region', { name: '取引管理' })
  const historyRow = panel.getByRole('row').nth(1)
  await expect(historyRow).toBeVisible()
  const historyText = await historyRow.innerText()
  const history = await page.evaluate(() => JSON.parse(localStorage.getItem('mango-fx-simulator-v1')).account.history)
  assert.equal(history.length, 1)
  await page.reload()
  assert.equal(await page.locator('html').getAttribute('data-interface-style'), 'glass')
  await page.getByRole('tab', { name: /取引履歴/ }).click()
  await expect(historyRow).toHaveText(historyText)
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('mango-fx-simulator-v1')).account.history), history)
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '取引履歴をCSV出力', exact: true }).click()
  assert.equal((await downloaded).suggestedFilename(), 'mango-fx-trades.csv')
  assert.deepEqual(errors, [])
  assert.deepEqual(requests, [])
  // A separate fresh browser also gets the actual offline welcome flow.
  const firstVisit = await browser.newContext({ offline: true })
  const welcomePage = await firstVisit.newPage()
  await welcomePage.route(documentUrl, route => route.fulfill({ status: 200, contentType: 'text/html; charset=utf-8', body: html }))
  welcomePage.on('pageerror', error => errors.push(error.message))
  welcomePage.on('request', request => { if (/^https?:/.test(request.url()) && request.url() !== documentUrl) requests.push(request.url()) })
  await welcomePage.goto(documentUrl)
  assert.equal(await welcomePage.locator('html').getAttribute('data-interface-style'), 'standard')
  await welcomePage.getByRole('heading', { name: 'MANGO FXへようこそ。', exact: true }).waitFor()
  const tutorial = welcomePage.getByRole('dialog')
  for (let step = 0; step < 10 && await tutorial.getByRole('button', { name: '次へ', exact: true }).count(); step += 1) await tutorial.getByRole('button', { name: '次へ', exact: true }).click()
  assert.equal(await tutorial.getByRole('button', { name: '会員登録へ進む', exact: true }).count(), 0)
  await tutorial.getByRole('button', { name: 'ゲストで始める', exact: true }).click()
  assert.equal(await welcomePage.getByRole('dialog').count(), 0)
  assert.equal(await welcomePage.evaluate(() => localStorage.getItem('mango-fx-onboarding-v1')), 'completed')
  await welcomePage.reload()
  await welcomePage.getByRole('button', { name: '買い注文を出す', exact: true }).waitFor()
  assert.equal(await welcomePage.getByRole('dialog').count(), 0)
  await firstVisit.close()
  assert.deepEqual(errors, [])
  assert.deepEqual(requests, [])
  console.log('PASS: standalone document runs with networking disabled, market advances without pause controls, glass choice persists on reload, first-visit tutorial can finish as a guest, trades and closes with history preserved, exports CSV, and loads no external assets. Direct file:// navigation is blocked by managed cloud Chromium policy and was not verified here.')
} finally { await browser.close() }
